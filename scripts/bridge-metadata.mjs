#!/usr/bin/env node
// Generate or verify src/bridge-metadata.generated.ts against the packaged bridge.

import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const bridgePath = path.join(root, 'bridge', 'codex-connector-bridge.mjs')
const generatedPath = path.join(root, 'src', 'bridge-metadata.generated.ts')

const hashBridge = async () => {
  const source = await readFile(bridgePath)
  return createHash('sha256').update(source).digest('hex')
}

const render = (digest) =>
  `// Generated by scripts/bridge-metadata.mjs — do not edit by hand.\n` +
  `export const BUNDLED_BRIDGE_SHA256 = '${digest}' as const\n`

const generate = async () => {
  const digest = await hashBridge()
  await writeFile(generatedPath, render(digest), 'utf8')
  process.stdout.write(`Wrote ${path.relative(root, generatedPath)}\n`)
  process.stdout.write(`BUNDLED_BRIDGE_SHA256=${digest}\n`)
}

const verify = async () => {
  const digest = await hashBridge()
  let current
  try {
    current = await readFile(generatedPath, 'utf8')
  } catch {
    throw new Error(
      `Missing ${path.relative(root, generatedPath)}. Run: bun run generate:bridge-metadata`,
    )
  }
  const expected = render(digest)
  if (current !== expected) {
    throw new Error(
      `Bridge metadata drift detected.\n` +
        `  bridge:   ${digest}\n` +
        `  metadata: out of date\n` +
        `Run: bun run generate:bridge-metadata`,
    )
  }
  process.stdout.write(`Bridge metadata OK (${digest})\n`)
}

const main = async () => {
  const command = process.argv[2] ?? 'verify'
  if (command === 'generate') {
    await generate()
    return
  }
  if (command === 'verify') {
    await verify()
    return
  }
  throw new Error(`Unknown command: ${command}. Use generate|verify.`)
}

main().catch((error) => {
  console.error(`codex-connector: ${error instanceof Error ? error.message : String(error)}`)
  process.exitCode = 1
})
